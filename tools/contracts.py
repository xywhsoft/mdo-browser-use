"""Generate matching C registration and JavaScript declarations from one file."""
import argparse
import copy
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    document = json.loads((ROOT / "contracts.json").read_text(encoding="utf-8"))
    rows = document["services"]
    if document["version"] != 1 or len({r["id"] for r in rows}) != len(rows):
        raise ValueError("Invalid or duplicate service contract")
    lines = ["/* Generated by tools/contracts.py. Do not edit. */",
             "static const BuService BuServices[] = {"]
    public = []
    wrappers = ["/* Generated by tools/contracts.py. Do not edit. */",
                "#ifndef MDO_BROWSER_USE_CLIENT_H", "#define MDO_BROWSER_USE_CLIENT_H",
                '#include "mdo/sdk.h"']
    for row in rows:
        if not row["id"].startswith("browseruse.") or not row["callback"].isidentifier():
            raise ValueError("Invalid service identity/callback")
        if row["effects"] not in ("MDO_TOOL_EFFECT_READ", "MDO_TOOL_EFFECT_READ | MDO_TOOL_EFFECT_EXTERNAL_SERVICE", "MDO_TOOL_EFFECT_READ | MDO_TOOL_EFFECT_WORKSPACE_WRITE | MDO_TOOL_EFFECT_EXTERNAL_SERVICE"):
            raise ValueError("Review the service effect mapping")
        stringify = lambda value: json.dumps(value, separators=(",", ":"), ensure_ascii=True)
        lines.append("    {%s, %s, %s, %s, %s, %s}," % (
            stringify(row["id"]), stringify(row["description"]),
            stringify(stringify(row["input"])), stringify(stringify(row["output"])),
            row["effects"], row["callback"]))
        public.append({key: row[key] for key in ("id", "description", "input", "output")})
        name = "mdoBrowserUse" + "".join(word.capitalize() for word in row["id"].split(".")[1:])
        wrappers.extend([
            f"static inline mdo_result {name}(const mdo_sdk_context_v1* C,const xvalue* P,xvalue** R,mdo_error_v1* E)",
            '{return mdoCall(C,"' + row["id"] + '",P,R,E);}'
        ])
    lines.extend(["};", ""])
    lines.append("static const BuToolSpec BuTools[] = {")
    tools = document.get("tools", [])
    if len({tool["id"] for tool in tools}) != len(tools):
        raise ValueError("Duplicate tool identity")
    for tool in tools:
        index = next(i for i, row in enumerate(rows) if row["id"] == tool["service"])
        if not tool["id"].isidentifier() or tool["effects"] not in ("MDO_TOOL_EFFECT_READ", "MDO_TOOL_EFFECT_READ | MDO_TOOL_EFFECT_EXTERNAL_SERVICE", "MDO_TOOL_EFFECT_READ | MDO_TOOL_EFFECT_WORKSPACE_WRITE | MDO_TOOL_EFFECT_EXTERNAL_SERVICE"):
            raise ValueError("Invalid tool identity/effects")
        schema = copy.deepcopy(rows[index]["input"])
        if "actions" in tool:
            original = schema["properties"]["action"]["enum"]
            if not set(tool["actions"]).issubset(original):
                raise ValueError("Tool action is outside its shared service contract")
            schema["properties"]["action"]["enum"] = tool["actions"]
        lines.append("    {%s, %s, %s, %s, %d}," % (
            stringify(tool["id"]), stringify(tool["description"]), stringify(stringify(schema)), tool["effects"], index))
    lines.extend(["};", ""])
    wrappers.extend(["#endif", ""])
    return {
        ROOT / "runtime/contracts.inc.h": "\n".join(lines),
        ROOT / "sdk/browser_use.h": "\n".join(wrappers),
        ROOT / "sdk/contracts.mjs": (
            "// Generated by tools/contracts.py. Do not edit.\n"
            "export const contractVersion = 1;\nexport const services = "
            + json.dumps(public, indent=2, ensure_ascii=False) + ";\n")
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                print("Stale generated contract:", path.relative_to(ROOT), file=sys.stderr)
                return 1
        elif not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    print("Shared C/JavaScript contracts", "verified" if args.check else "generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
