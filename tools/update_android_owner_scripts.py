"""Generate/check Android owner functions from the reviewed Windows helpers.

One authoritative helper body, no runtime dependency. Unknown edits and pending
staging files are preserved rather than silently overwritten.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'host/native-frames.inc.hpp'
OUTPUT=ROOT/'host/android/MdoBrowserCdpOwnerScripts.java'
FUNCTIONS={'GEOMETRY':'xb_frame_owner_geometry','UPLOAD_POLICY':'xb_frame_owner_upload_policy','CAPTURE':'xb_frame_owner_capture'}


def render(text):
    bodies={}
    for name,symbol in FUNCTIONS.items():
        pattern=r'static const char\* '+re.escape(symbol)+r'=R"js\((.*?)\)js";'
        matches=re.findall(pattern,text,re.DOTALL)
        if len(matches)!=1:raise RuntimeError('Owner helper is missing or ambiguous: '+symbol)
        body=matches[0]
        if not body.startswith('function(') or not body.endswith('}') or len(body.encode('utf-8'))>16384:
            raise RuntimeError('Owner helper shape/size is invalid: '+symbol)
        bodies[name]=body
    digest=hashlib.sha256(json.dumps(bodies,sort_keys=True).encode()).hexdigest()
    rows=['package org.xserver.android;','','/** Generated by tools/update_android_owner_scripts.py from the reviewed',
          ' * host/native-frames.inc.hpp owner functions. Do not edit this file.',
          ' * Helper SHA-256: '+digest+' */','final class MdoBrowserCdpOwnerScripts {']
    for name,body in bodies.items():rows.append('    static final String '+name+'='+json.dumps(body,ensure_ascii=True)+';')
    rows+=['    private MdoBrowserCdpOwnerScripts(){}','}','']
    return '\n'.join(rows)


def verify():
    if SOURCE.is_symlink() or OUTPUT.is_symlink():raise RuntimeError('Linked owner helper source preserved')
    wanted=render(SOURCE.read_text(encoding='utf-8'))
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8')!=wanted:
        raise RuntimeError('Android owner helpers are stale; review and run tools/update_android_owner_scripts.py')


def main(check=False):
    if check:verify();print('Reviewed owner helpers match both native adapters');return
    if SOURCE.is_symlink() or OUTPUT.is_symlink():raise RuntimeError('Linked owner helper source preserved')
    wanted=render(SOURCE.read_text(encoding='utf-8'))
    if OUTPUT.exists() and OUTPUT.read_text(encoding='utf-8')!=wanted:
        result=subprocess.run(['git','show','HEAD:host/android/MdoBrowserCdpOwnerScripts.java'],cwd=ROOT,capture_output=True)
        if result.returncode or OUTPUT.read_bytes()!=result.stdout.replace(b'\r\n',b'\n'):
            raise RuntimeError('Unreviewed generated owner helper edit preserved')
    pending=OUTPUT.with_suffix('.owner.pending')
    if pending.exists() or pending.is_symlink():raise RuntimeError('Interrupted owner helper generation preserved')
    pending.write_text(wanted,encoding='utf-8',newline='\n');pending.replace(OUTPUT);verify()
    print('Generated reviewed Android owner helpers')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    try:main(args.check)
    except (RuntimeError,OSError,ValueError) as error:print(error,file=sys.stderr);raise SystemExit(1)
